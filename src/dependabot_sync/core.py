import subprocess
from pathlib import Path
from typing import Optional

def is_git_root() -> bool:
    """Check if the current working directory is a git repository root."""
    try:
        # Check if we are inside a git repository
        res_inside = subprocess.run(
            ["git", "rev-parse", "--is-inside-work-tree"],
            capture_output=True, text=True, check=True
        )
        if res_inside.stdout.strip() != "true":
            return False
            
        # Check if the current directory is indeed the root of that worktree
        res_root = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, check=True
        )
        toplevel = Path(res_root.stdout.strip()).resolve()
        cwd = Path.cwd().resolve()
        return toplevel == cwd
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False

def get_github_user() -> Optional[str]:
    """Retrieve the current authenticated GitHub user login using gh CLI."""
    try:
        res = subprocess.run(
            ["gh", "api", "user", "--jq", ".login"],
            capture_output=True, text=True, check=True
        )
        user = res.stdout.strip()
        return user if user else None
    except Exception:
        return None

def generate_dependabot_config(interval: str = "daily", limit: int = 3, assignee: Optional[str] = None) -> str:
    """Generate a standard, low-noise dependabot.yml configuration string."""
    assignee_block = ""
    if assignee:
        assignee_block = f"\n    assignees:\n      - {assignee}"

    config = f"""# Standard Dependabot configuration generated by dependabot-sync
version: 2
updates:
  # Python packages configuration
  - package-ecosystem: "pip"
    directory: "/"
    schedule:
      interval: "{interval}"{assignee_block}
    groups:
      python-dependencies:
        patterns:
          - "*"
    open-pull-requests-limit: {limit}

  # GitHub Actions workflows configuration
  - package-ecosystem: "github-actions"
    directory: "/"
    schedule:
      interval: "{interval}"{assignee_block}
    open-pull-requests-limit: {limit}
"""
    return config

def write_config(target_dir: Path, content: str, force: bool = False) -> Path:
    """Write the dependabot.yml to .github/ folder with safety checks."""
    github_dir = target_dir / ".github"
    github_dir.mkdir(parents=True, exist_ok=True)
    
    config_file = github_dir / "dependabot.yml"
    if config_file.exists() and not force:
        raise FileExistsError(f"Dependabot configuration already exists at {config_file}. Use --force to overwrite.")
        
    config_file.write_text(content, encoding="utf-8")
    return config_file
